/**
 * Writes src/content/image-library.generated.ts listing the images in public/images,
 * so the admin image picker works on any host (incl. serverless, where public/ isn't on disk).
 * Runs automatically before `dev` and `build`.
 */
import fs from "node:fs";
import path from "node:path";

const dir = path.join(process.cwd(), "public/images");
const files = fs
  .readdirSync(dir)
  .filter((f) => /\.(webp|png|jpe?g|svg|avif)$/i.test(f))
  .sort()
  .map((f) => `/images/${f}`);
const out = `// AUTO-GENERATED by scripts/index-images.ts — do not edit.\nexport const IMAGE_LIBRARY: string[] = ${JSON.stringify(files, null, 2)};\n`;
fs.writeFileSync(path.join(process.cwd(), "src/content/image-library.generated.ts"), out);
console.log(`indexed ${files.length} images`);
